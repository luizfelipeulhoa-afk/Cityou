import fs from 'node:fs'
import { chromium, python, browserOptions } from './runtime.mjs'
const browser=await chromium.launch({...browserOptions,args:['--no-first-run','--no-default-browser-check']})
const page=await browser.newPage({viewport:{width:1440,height:960},deviceScaleFactor:1})
const errors=[]
page.on('pageerror',error=>errors.push(error.message))
page.on('console',message=>{if(message.type()==='error') errors.push(message.text().slice(0,650))})
await page.goto('http://127.0.0.1:8766/city.html',{waitUntil:'networkidle'})
await page.waitForFunction(()=>window.__fifonesCity?.state?.placements.length>0)
await page.waitForTimeout(1200)
fs.mkdirSync('.verification',{recursive:true})
await page.screenshot({path:'.verification/city-desktop.png',fullPage:true})
console.log(JSON.stringify({title:await page.title(),stats:await page.evaluate(()=>window.__fifonesCity.engine.stats()),errors,buttons:await page.getByRole('button').allTextContents()}))
await page.getByRole('button',{name:'Entardecer',exact:true}).click()
await page.waitForTimeout(500)
await page.screenshot({path:'.verification/city-dusk.png',fullPage:true})
await page.getByRole('button',{name:'Agenda',exact:true}).click()
await page.waitForTimeout(800)
console.log('workspace',await page.locator('iframe').count())
await page.keyboard.press('Escape')
await page.setViewportSize({width:390,height:844})
await page.waitForTimeout(500)
await page.screenshot({path:'.verification/city-mobile.png',fullPage:true})
console.log('responsive',await page.evaluate(()=>({inner:innerWidth,scroll:document.documentElement.scrollWidth})))
await browser.close()
